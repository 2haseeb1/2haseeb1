/**
 * The widget layout is compiled into a string and evaluated in a different
 * process, which makes it uniquely easy to break in ways no type checker or
 * render test can see. These tests close that gap by inspecting the compiled
 * source string itself.
 *
 * A failure here means the widget would render fine in development and fail on a
 * device, so treat these as load-bearing rather than cosmetic.
 */

import { parse } from '@babel/parser';
import _traverse from '@babel/traverse';

import BlinkWidget from '@/widgets/BlinkWidget';
import { EMPTY_SNAPSHOT, buildWidgetSnapshot } from '@/features/widget/snapshot';
import type { Task } from '@/lib/types';

// @babel/traverse ships CJS; interop differs between ts-jest and babel-jest.
const traverse = ((_traverse as unknown as { default?: typeof _traverse }).default ??
  _traverse) as typeof _traverse;

